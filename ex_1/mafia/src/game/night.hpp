// Правила ночи — чистые функции: решение мафии и разрешение ночи целиком.
// Никакого состояния и нитей: на вход — все собранные ходы, на выход — итог.
// Поэтому итог не зависит от того, в каком порядке ходы пришли.
#pragma once

#include "game/types.hpp"

#include <optional>
#include <utility>
#include <vector>

namespace mafia {

// ---------------------------------------------------------------------------
// Общее решение мафии
// ---------------------------------------------------------------------------

struct MafiaDecision {
    std::optional<PlayerId> victim;  // решено: большинство или голос Босса при равенстве
    std::vector<PlayerId> tied;      // не решено: равенство, а Босс голосовал не за лидера
};

// votes: (мафиози, его цель). boss — старший живой мафиози.
//   единственный лидер              -> он;
//   равенство и Босс за одного из   -> выбор Босса;
//   равенство, Босс за другого      -> tied: ведущий спросит Босса отдельно.
MafiaDecision decide_mafia(const std::vector<std::pair<PlayerId, PlayerId>>& votes, PlayerId boss);

// ---------------------------------------------------------------------------
// Разрешение ночи
// ---------------------------------------------------------------------------

struct Attack {
    PlayerId target = 0;
    RoleKind by = RoleKind::Mafioso;  // кто напал: мафия, маньяк, комиссар (выстрел)
};

struct NightOutcome {
    std::vector<PlayerId> deaths;  // погибнут утром; по возрастанию, без повторов
    std::vector<PlayerId> saved;   // на них напали, но доктор спас
};

// Лечение перекрывает ЛЮБОЕ нападение на цель (мафия, маньяк, выстрел комиссара).
// Несколько нападений на одного — одна смерть. Порядок attacks не важен.
NightOutcome resolve_night(const std::vector<Attack>& attacks, std::optional<PlayerId> heal);

}  // namespace mafia
